#!/bin/sh
# Builds ed.wasm from ed.c and port.c, for WebAssembly 1.0, which is all that
# wasmc compiles, and writes it as a static const array to ../main/ed_wasm.h,
# for the firmware. Needs clang with the wasm32 target, wasm-ld and xxd.
#
#   -std=gnu89 -w             ed.c is K&R C (plain "return;" in int functions:
#   -Wno-return-mismatch      an error by default)
#   -fno-builtin              clang must not call memset & co.
#   -fno-strict-aliasing,     ed.c walks arrays with pointers past their
#   -fno-strict-overflow      bounds and casts them freely
#   wasm-ld, not clang        with wasm-opt in the PATH clang runs it after
#                             the link, and it adds opcodes wasmc rejects
#   --fatal-warnings          a signature mismatch, easy in K&R C, would link
#                             as a stub that traps
#   --export=__heap_base,     how WAMR and wasmc find the C stack: without them
#   --export=__data_end       its overflow goes unchecked
#   -z stack-size=8192        8 KiB of C stack, in one page of linear memory
#                             (ed grows it for long files)
set -e
cd "$(dirname "$0")"
out=${1:-../host/build/ed.wasm}
mkdir -p "$(dirname "$out")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cflags="--target=wasm32 -mcpu=mvp -Oz -nostdlib -fno-builtin
        -fno-strict-aliasing -fno-strict-overflow"
clang $cflags -std=gnu89 -w -Wno-return-mismatch -c ed.c -o "$tmp/ed.o"
clang $cflags -std=gnu17 -Wall -Wextra -c port.c -o "$tmp/port.o"
wasm-ld --no-entry --gc-sections --strip-all --fatal-warnings \
    --export=__heap_base --export=__data_end \
    --initial-memory=65536 -z stack-size=8192 \
    -o "$out" "$tmp/ed.o" "$tmp/port.o"
{
    echo "/* Generated by wasm/build.sh from wasm/ed.c and port.c: do not edit. */"
    echo "#pragma once"
    echo
    xxd -i -n ed_wasm "$out" |
        sed 's/^unsigned char/static const unsigned char/;
             s/^unsigned int/static const unsigned int/'
} > ../main/ed_wasm.h
echo "$out: $(wc -c < "$out") bytes"
