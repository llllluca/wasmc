#!/bin/sh
# Builds the WebAssembly programs (*.c) and writes them, as static const
# arrays, to ../main/wasm_modules.h. Needs clang with the wasm32 target,
# wasm-ld (lld) and xxd.
#
#   -mcpu=mvp                 WebAssembly 1.0 only, all that wasmc compiles
#   -nostdlib -fno-builtin    no libc: clang must not call memset & co.
#   --no-entry                a library of exported functions, no _start
#   --initial-memory=65536    one 64 KiB page of linear memory ...
#   -z stack-size=8192        ... of which 8 KiB of C stack
set -e
cd "$(dirname "$0")"
out=../main/wasm_modules.h
{
    echo "/* Generated by wasm/build.sh from the C files in wasm/: do not edit. */"
    echo "#pragma once"
    echo
} > "$out"
for src in fib.c sieve.c collatz.c mandel.c; do
    name=$(basename "$src" .c)
    clang --target=wasm32 -mcpu=mvp -O2 -nostdlib -fno-builtin \
        -Wl,--no-entry -Wl,--initial-memory=65536 -Wl,-z,stack-size=8192 \
        -Wl,--strip-all -o "$name.wasm" "$src"
    xxd -i -n "${name}_wasm" "$name.wasm" |
        sed 's/^unsigned char/static const unsigned char/;
             s/^unsigned int/static const unsigned int/' >> "$out"
    echo "$name.wasm: $(wc -c < "$name.wasm") bytes"
done
